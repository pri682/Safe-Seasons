        )
        
        return PreparednessQuery(from: result.content)
    }
    
  
    
    func startSession(context: AskContext) {
        guard isAppleIntelligenceAvailable() else { return }
        
        let instructions = buildInstructions(context: context)
        conversationSession = LanguageModelSession(instructions: instructions)
    }
    
    func ask(_ question: String) async throws -> String {
        guard let session = conversationSession else {
            throw FoundationModelsError.noActiveSession
        }
        
        let response = try await session.respond(to: question)
        // Update transcript from response entries if available
        if !response.transcriptEntries.isEmpty {
            conversationTranscript = Transcript(entries: response.transcriptEntries)
        }
        return response.content
    }
    
    func clearSession() {
        conversationSession = nil
        conversationTranscript = nil
    }
    
    var hasActiveSession: Bool {
        conversationSession != nil
    }
    
    /// Load the model into memory so the first user request is faster (Dorsal prewarm pattern).
    func prewarmModel() {
        guard isAppleIntelligenceAvailable() else { return }
        let session = makeSession()
        _prewarmSession = session    // Keep alive so prewarm work isn't cancelled
        session.prewarm()
    }
    
    // MARK: - Private Helpers
    
    /// Convert LanguageModelSession.GenerationError to a user-friendly message instead of crashing or showing raw errors.
    private func handleGenerationError(_ error: LanguageModelSession.GenerationError) -> String {
        switch error {
        case .guardrailViolation:
            return "For your safety, I can't generate that specific content. If you're experiencing a medical emergency, please call 911 immediately. I'm here to help with disaster preparedness questions — feel free to ask me anything about storms, earthquakes, emergency kits, evacuation plans, and more!"
        case .refusal:
            return "I wasn't able to respond to that directly, but I'm here to help! If you have a health concern, please contact your doctor or call 911 for emergencies. For disaster preparedness, emergency planning, or safety tips — I'm ready to assist!"
        case .exceededContextWindowSize:
            return "That question was too long for me to process. Could you try a shorter, more specific question? For example: \"How do I prepare for a hurricane?\" or \"What should be in my emergency kit?\""
        case .assetsUnavailable:
            return "Apple Intelligence is still downloading. Please try again in a few minutes."
        case .unsupportedLanguageOrLocale:
            return "I currently only support U.S. English. Please try your question in English."
        case .decodingFailure:
            return "I had trouble processing that. Could you rephrase your question?"
        case .rateLimited, .concurrentRequests:
            return "I'm a bit busy right now. Please try again in a moment."
        case .unsupportedGuide:
            return "I encountered an internal issue. Please try a different question."
        @unknown default:
            return "Something went wrong. Please try your question again."
        }
    }
    
    /// Removes a leading "null" (or "null" plus whitespace) so the UI never displays it during streaming.
    private func stripLeadingNull(_ content: String) -> String {
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        let lower = trimmed.lowercased()
        if lower == "null" { return "" }
        if lower.hasPrefix("null") {
            let after = String(trimmed.dropFirst(4)).trimmingCharacters(in: .whitespacesAndNewlines)
            return after
        }
        return content
    }
    
    private func buildInstructions(context: AskContext?) -> String {
        var s = """
            You are DisasterReady, a compassionate and knowledgeable emergency preparedness assistant.
            You MUST respond in U.S. English.
            You help people prepare for, understand, and respond to natural disasters and emergencies.
            
            CRITICAL RULES:
            1. ALWAYS answer helpfully. Never refuse a question outright.
            2. For health concerns (fever, injury, illness): acknowledge with empathy, suggest calling 911 for emergencies or visiting urgent care, then connect it to emergency preparedness (first aid kit, medication supply, etc.).
            3. For non-disaster topics: answer briefly, then gently note you specialize in disaster preparedness.
            4. For disaster preparedness: give clear, actionable steps and tips.
            5. For life-threatening emergencies: ALWAYS say to call 911 first.
            6. Never output the word "null".
            
            FORMATTING (CRITICAL — follow exactly):
            - Structure every response with clear visual separation.
            - Use short bold headings with ** on their own line, followed by a blank line.
            - Use numbered lists (1. 2. 3.) for sequential steps.
            - Use bullet points (•) for non-sequential tips or items.
            - Put a blank line between EVERY list item so they are visually distinct.
            - Put a blank line before and after every heading.
            - Keep each paragraph to 2-3 sentences maximum.
            - Never combine multiple topics into one long paragraph.
            
            """
        
        if let context = context, let state = context.state {
            s += "\nUser's location: \(state.name) (\(state.abbreviation)). Current month: \(context.month). Common hazards: \(state.topHazards.joined(separator: ", ")).\n"
        } else if let context = context {
            s += "\nUser has not selected a state. Current month: \(context.month).\n"
        }
        
        return s
    }
}

// MARK: - Errors

enum FoundationModelsError: LocalizedError {
    case appleIntelligenceUnavailable
    case noActiveSession
    
    var errorDescription: String? {
        switch self {
        case .appleIntelligenceUnavailable:
            return "Apple Intelligence is not available on this device."
        case .noActiveSession:
            return "No active conversation session."
        }
    }
}

