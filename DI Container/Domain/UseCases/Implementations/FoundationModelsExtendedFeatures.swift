    // MARK: - SummarizationUseCaseProtocol
    
    func summarizeDisaster(_ disaster: Disaster) async throws -> String {
        guard isAppleIntelligenceAvailable() else {
            throw FoundationModelsError.appleIntelligenceUnavailable
